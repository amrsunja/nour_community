// =============================================================================
// Donation attestation — neutral proof of gift, available in EVERY country.
//
// This is NOT a tax document and says so, in a bordered disclaimer, in its own
// locale. It exists so that a mosque outside a supported tax regime still has
// something useful to hand a donor instead of a dead button, without Nour
// producing a document that could be mistaken for a tax receipt.
// =============================================================================

